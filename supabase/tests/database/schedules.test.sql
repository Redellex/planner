-- Risk #5/#6, database half: a draft schedule is manager-only, needs its month lock and blocks the unlock, is replaced
-- atomically, and holds only allowed shifts: the 9 shapes, the station-day month rule and no overlap station-wide.
-- A deleted account's shifts become uncovered. Oracles: plan generate-monthly-schedule ("Station day and shift model
-- (agreed)", Phase 1 contract), roadmap S-03 decisions (employees cannot read drafts in S-03; unlock refused while a
-- draft exists), PRD FR-003. Refused writes are checked as postgres afterwards: as the denied actor, RLS would hide
-- the rows anyway.
begin;
select plan(50);

-- Station months, derived once; now() is fixed for the transaction.
select
  (s + interval '1 month')::date as m1,
  (s + interval '2 months')::date as m2
from (select date_trunc('month', now() at time zone 'Europe/Warsaw') as s) station
\gset

-- Fixtures: employees A and B, manager Mg. The signup trigger creates their employee profiles.
insert into auth.users (id, email) values
  ('10000000-0000-4000-8000-0000000000a4', 'sa@db-rules.test'),
  ('10000000-0000-4000-8000-0000000000b4', 'sb@db-rules.test'),
  ('10000000-0000-4000-8000-0000000000c4', 'smg@db-rules.test');
update public.profiles set role = 'manager' where id = '10000000-0000-4000-8000-0000000000c4';

-- M+1 is locked with no draft, M+2 has neither lock nor draft, whatever the local or CI state.
delete from public.schedules where month in (:'m1', :'m2');
delete from public.availability_locks where month = :'m2';
insert into public.availability_locks (month) values (:'m1') on conflict do nothing;

-- Drafts as the endpoint sends them: v1 is 12+12 on day 1 of M+1, v2 is 8+8+8 on day 1 of M+1, bad is v2 plus one
-- 12h shift starting 07:00 on day 3, m2 is one shift in M+2.
select
  jsonb_build_array(
    jsonb_build_object('starts_at', :'m1'::date + interval '06:00', 'ends_at', :'m1'::date + interval '18:00',
      'employee_id', '10000000-0000-4000-8000-0000000000a4'),
    jsonb_build_object('starts_at', :'m1'::date + interval '18:00', 'ends_at', :'m1'::date + interval '1 day 06:00',
      'employee_id', null)
  )::text as draft_v1,
  jsonb_build_array(
    jsonb_build_object('starts_at', :'m1'::date + interval '06:00', 'ends_at', :'m1'::date + interval '14:00',
      'employee_id', '10000000-0000-4000-8000-0000000000a4'),
    jsonb_build_object('starts_at', :'m1'::date + interval '14:00', 'ends_at', :'m1'::date + interval '22:00',
      'employee_id', '10000000-0000-4000-8000-0000000000c4'),
    jsonb_build_object('starts_at', :'m1'::date + interval '22:00', 'ends_at', :'m1'::date + interval '1 day 06:00',
      'employee_id', null)
  )::text as draft_v2,
  jsonb_build_array(
    jsonb_build_object('starts_at', :'m1'::date + interval '06:00', 'ends_at', :'m1'::date + interval '14:00',
      'employee_id', '10000000-0000-4000-8000-0000000000a4'),
    jsonb_build_object('starts_at', :'m1'::date + interval '14:00', 'ends_at', :'m1'::date + interval '22:00',
      'employee_id', '10000000-0000-4000-8000-0000000000c4'),
    jsonb_build_object('starts_at', :'m1'::date + interval '2 days 07:00',
      'ends_at', :'m1'::date + interval '2 days 19:00', 'employee_id', null)
  )::text as draft_bad,
  jsonb_build_array(
    jsonb_build_object('starts_at', :'m2'::date + interval '06:00', 'ends_at', :'m2'::date + interval '18:00',
      'employee_id', null)
  )::text as draft_m2
\gset

-- Mg creates a draft for locked M+1 and reads it
set local role authenticated;
set local request.jwt.claims = '{"sub":"10000000-0000-4000-8000-0000000000c4","role":"authenticated"}';
select lives_ok(
  format($$ select public.replace_schedule_draft(%L::date, %L::jsonb) $$, :'m1', :'draft_v1'),
  'Mg can create a draft for locked month M+1'
);
select is(
  (select count(*) from public.schedule_shifts where month = :'m1'),
  2::bigint,
  'Mg reads both shifts of the M+1 draft'
);
select is(
  (select generated_by from public.schedules where month = :'m1'),
  '10000000-0000-4000-8000-0000000000c4'::uuid,
  'Mg reads the M+1 draft row, generated by Mg'
);
select throws_ok(
  format($$ select public.replace_schedule_draft(%L::date, %L::jsonb) $$, :'m2', :'draft_m2'),
  '23503', null,
  'Mg cannot create a draft for month M+2, which has no lock'
);
reset role;
select is(
  (select count(*) from public.schedules where month = :'m2'),
  0::bigint,
  'no draft row exists for M+2 after the refused call'
);

select
  (select string_agg(id::text, ',' order by id) from public.schedule_shifts where month = :'m1') as v1_ids,
  (select row(generated_at, generated_by)::text from public.schedules where month = :'m1') as v1_row
\gset

-- Employee A against the draft
set local role authenticated;
set local request.jwt.claims = '{"sub":"10000000-0000-4000-8000-0000000000a4","role":"authenticated"}';
select is_empty(
  format($$ select month from public.schedules where month = %L $$, :'m1'),
  'A cannot read the M+1 draft row'
);
select is_empty(
  format($$ select id from public.schedule_shifts where month = %L $$, :'m1'),
  'A cannot read the M+1 draft shifts, including their own'
);
select throws_ok(
  format($$ insert into public.schedules (month) values (%L) $$, :'m2'),
  '42501', null,
  'A cannot insert a draft row'
);
select throws_ok(
  format($$ insert into public.schedule_shifts (month, starts_at, ends_at) values (%L, %L, %L) $$,
    :'m1', :'m1'::date + interval '2 days 06:00', :'m1'::date + interval '2 days 18:00'),
  '42501', null,
  'A cannot insert a shift into the M+1 draft'
);
select is_empty(
  format($$ delete from public.schedule_shifts where month = %L returning id $$, :'m1'),
  'A deleting the M+1 draft shifts matches no rows'
);
select is_empty(
  format($$ delete from public.schedules where month = %L returning month $$, :'m1'),
  'A deleting the M+1 draft row matches no rows'
);
select throws_ok(
  format($$ select public.replace_schedule_draft(%L::date, %L::jsonb) $$, :'m1', :'draft_v2'),
  '42501', null,
  'A cannot replace the M+1 draft through the RPC'
);
reset role;
select is(
  (select string_agg(id::text, ',' order by id) from public.schedule_shifts where month = :'m1'),
  :'v1_ids',
  'the M+1 draft shifts are unchanged after A''s writes'
);
select is(
  (select row(generated_at, generated_by)::text from public.schedules where month = :'m1'),
  :'v1_row',
  'the M+1 draft row is unchanged after A''s writes'
);

-- Replace semantics: a second call replaces every row; a call with one bad row changes nothing
set local role authenticated;
set local request.jwt.claims = '{"sub":"10000000-0000-4000-8000-0000000000c4","role":"authenticated"}';
select lives_ok(
  format($$ select public.replace_schedule_draft(%L::date, %L::jsonb) $$, :'m1', :'draft_v2'),
  'Mg can replace the M+1 draft'
);
reset role;
select is(
  (select count(*) from public.schedule_shifts where id::text = any(string_to_array(:'v1_ids', ','))),
  0::bigint,
  'no shift of the first M+1 draft remains after the replace'
);
select is(
  (select count(*) from public.schedule_shifts where month = :'m1'),
  3::bigint,
  'the replaced M+1 draft has exactly the 3 new shifts'
);

select string_agg(id::text, ',' order by id) as v2_ids
from public.schedule_shifts
where month = :'m1'
\gset

set local role authenticated;
set local request.jwt.claims = '{"sub":"10000000-0000-4000-8000-0000000000c4","role":"authenticated"}';
select throws_ok(
  format($$ select public.replace_schedule_draft(%L::date, %L::jsonb) $$, :'m1', :'draft_bad'),
  '23514', null,
  'Mg cannot replace the M+1 draft with a set containing one wrongly shaped shift'
);
reset role;
select is(
  (select string_agg(id::text, ',' order by id) from public.schedule_shifts where month = :'m1'),
  :'v2_ids',
  'the M+1 draft is intact after the refused replace'
);

-- Shift constraints, written by Mg straight into the M+1 draft; each shape on its own station day
set local role authenticated;
set local request.jwt.claims = '{"sub":"10000000-0000-4000-8000-0000000000c4","role":"authenticated"}';
select lives_ok(
  format($$ insert into public.schedule_shifts (month, starts_at, ends_at) values (%L, %L, %L) $$,
    :'m1', :'m1'::date + interval '9 days 06:00', :'m1'::date + interval '9 days 18:00'),
  'Mg can add a 06:00 12h shift'
);
select lives_ok(
  format($$ insert into public.schedule_shifts (month, starts_at, ends_at) values (%L, %L, %L) $$,
    :'m1', :'m1'::date + interval '10 days 18:00', :'m1'::date + interval '11 days 06:00'),
  'Mg can add an 18:00 12h shift'
);
select lives_ok(
  format($$ insert into public.schedule_shifts (month, starts_at, ends_at) values (%L, %L, %L) $$,
    :'m1', :'m1'::date + interval '11 days 06:00', :'m1'::date + interval '11 days 14:00'),
  'Mg can add a 06:00 8h shift'
);
select lives_ok(
  format($$ insert into public.schedule_shifts (month, starts_at, ends_at) values (%L, %L, %L) $$,
    :'m1', :'m1'::date + interval '12 days 14:00', :'m1'::date + interval '12 days 22:00'),
  'Mg can add a 14:00 8h shift'
);
select lives_ok(
  format($$ insert into public.schedule_shifts (month, starts_at, ends_at) values (%L, %L, %L) $$,
    :'m1', :'m1'::date + interval '13 days 22:00', :'m1'::date + interval '14 days 06:00'),
  'Mg can add a 22:00 8h shift'
);
select lives_ok(
  format($$ insert into public.schedule_shifts (month, starts_at, ends_at) values (%L, %L, %L) $$,
    :'m1', :'m1'::date + interval '14 days 06:00', :'m1'::date + interval '14 days 12:00'),
  'Mg can add a 06:00 6h shift'
);
select lives_ok(
  format($$ insert into public.schedule_shifts (month, starts_at, ends_at) values (%L, %L, %L) $$,
    :'m1', :'m1'::date + interval '15 days 12:00', :'m1'::date + interval '15 days 18:00'),
  'Mg can add a 12:00 6h shift'
);
select lives_ok(
  format($$ insert into public.schedule_shifts (month, starts_at, ends_at) values (%L, %L, %L) $$,
    :'m1', :'m1'::date + interval '16 days 18:00', :'m1'::date + interval '17 days'),
  'Mg can add an 18:00 6h shift'
);
select lives_ok(
  format($$ insert into public.schedule_shifts (month, starts_at, ends_at) values (%L, %L, %L) $$,
    :'m1', :'m1'::date + interval '18 days 00:00', :'m1'::date + interval '18 days 06:00'),
  'Mg can add a 00:00 6h shift'
);
select lives_ok(
  format($$ insert into public.schedule_shifts (month, starts_at, ends_at) values (%L, %L, %L) $$,
    :'m1', :'m2'::date + interval '00:00', :'m2'::date + interval '06:00'),
  'Mg can add 00:00-06:00 on the 1st of M+2 to M+1, the month of its station day'
);
select throws_ok(
  format($$ insert into public.schedule_shifts (month, starts_at, ends_at) values (%L, %L, %L) $$,
    :'m1', :'m1'::date + interval '18 days 06:00', :'m1'::date + interval '18 days 13:00'),
  '23514', null,
  'Mg cannot add a 7h shift'
);
select throws_ok(
  format($$ insert into public.schedule_shifts (month, starts_at, ends_at) values (%L, %L, %L) $$,
    :'m1', :'m1'::date + interval '19 days 07:00', :'m1'::date + interval '19 days 19:00'),
  '23514', null,
  'Mg cannot add a 12h shift starting 07:00'
);
select throws_ok(
  format($$ insert into public.schedule_shifts (month, starts_at, ends_at) values (%L, %L, %L) $$,
    :'m1', :'m1'::date + interval '00:00', :'m1'::date + interval '06:00'),
  '23514', null,
  'Mg cannot add 00:00-06:00 on the 1st of M+1 to M+1: its station day belongs to M'
);
select lives_ok(
  format($$ insert into public.schedule_shifts (month, starts_at, ends_at, employee_id) values (%L, %L, %L, %L) $$,
    :'m1', :'m1'::date + interval '20 days 06:00', :'m1'::date + interval '20 days 18:00',
    '10000000-0000-4000-8000-0000000000a4'),
  'Mg can add a 06:00-18:00 shift for A'
);
select throws_ok(
  format($$ insert into public.schedule_shifts (month, starts_at, ends_at, employee_id) values (%L, %L, %L, %L) $$,
    :'m1', :'m1'::date + interval '20 days 12:00', :'m1'::date + interval '20 days 18:00',
    '10000000-0000-4000-8000-0000000000c4'),
  '23P01', null,
  'Mg cannot add a 12:00-18:00 shift for Mg overlapping A''s shift'
);
select lives_ok(
  format($$ insert into public.schedule_shifts (month, starts_at, ends_at, employee_id) values (%L, %L, %L, %L) $$,
    :'m1', :'m1'::date + interval '21 days 18:00', :'m1'::date + interval '22 days 06:00',
    '10000000-0000-4000-8000-0000000000a4'),
  'Mg can add an 18:00-06:00 shift for A'
);
select lives_ok(
  format($$ insert into public.schedule_shifts (month, starts_at, ends_at, employee_id) values (%L, %L, %L, %L) $$,
    :'m1', :'m1'::date + interval '22 days 06:00', :'m1'::date + interval '22 days 12:00',
    '10000000-0000-4000-8000-0000000000a4'),
  'Mg can add a 06:00-12:00 shift touching the previous night''s 18:00-06:00'
);
reset role;

-- Deleting an account leaves its shift uncovered
insert into public.schedule_shifts (id, month, starts_at, ends_at, employee_id)
values ('10000000-0000-4000-8000-00000000f401', :'m1', :'m1'::date + interval '24 days 06:00',
  :'m1'::date + interval '24 days 18:00', '10000000-0000-4000-8000-0000000000b4');
delete from auth.users where id = '10000000-0000-4000-8000-0000000000b4';
select results_eq(
  $$ select employee_id from public.schedule_shifts where id = '10000000-0000-4000-8000-00000000f401' $$,
  $$ values (null::uuid) $$,
  'B''s shift remains, uncovered, after B''s account is deleted'
);

-- The lock and the draft: no unlock while the draft exists, unlock after it is discarded
set local role authenticated;
set local request.jwt.claims = '{"sub":"10000000-0000-4000-8000-0000000000c4","role":"authenticated"}';
select throws_ok(
  format($$ delete from public.availability_locks where month = %L $$, :'m1'),
  '23503', null,
  'Mg cannot unlock M+1 while it has a draft'
);
reset role;
select is(
  (select count(*) from public.availability_locks where month = :'m1'),
  1::bigint,
  'the M+1 lock remains after the refused unlock'
);
set local role authenticated;
set local request.jwt.claims = '{"sub":"10000000-0000-4000-8000-0000000000c4","role":"authenticated"}';
select isnt_empty(
  format($$ delete from public.schedules where month = %L returning month $$, :'m1'),
  'Mg can discard the M+1 draft'
);
reset role;
select is(
  (select count(*) from public.schedule_shifts where month = :'m1'),
  0::bigint,
  'discarding the M+1 draft removes its shifts'
);
set local role authenticated;
set local request.jwt.claims = '{"sub":"10000000-0000-4000-8000-0000000000c4","role":"authenticated"}';
select isnt_empty(
  format($$ delete from public.availability_locks where month = %L returning month $$, :'m1'),
  'Mg can unlock M+1 once its draft is discarded'
);
reset role;

-- Privileges: no table-level UPDATE (S-04 must grant update columns explicitly), no anon RPC.
select is(has_table_privilege('authenticated', 'public.schedules', 'UPDATE'), false,
  'authenticated has no table-level UPDATE on schedules');
select is(has_table_privilege('authenticated', 'public.schedule_shifts', 'UPDATE'), false,
  'authenticated has no table-level UPDATE on schedule_shifts');
select is(has_table_privilege('anon', 'public.schedules', 'UPDATE'), false,
  'anon has no table-level UPDATE on schedules');
select is(has_table_privilege('anon', 'public.schedule_shifts', 'UPDATE'), false,
  'anon has no table-level UPDATE on schedule_shifts');
select is(has_function_privilege('anon', 'public.replace_schedule_draft(date, jsonb)', 'execute'), false,
  'anon cannot execute replace_schedule_draft');

-- anon gets nothing: a draft for M+1 exists again (written as the owner).
insert into public.availability_locks (month) values (:'m1') on conflict do nothing;
insert into public.schedules (month) values (:'m1');
insert into public.schedule_shifts (month, starts_at, ends_at) values
  (:'m1', :'m1'::date + interval '06:00', :'m1'::date + interval '18:00');
select is((select count(*) from public.schedule_shifts where month = :'m1'), 1::bigint,
  'control: the M+1 draft has a shift');
set local role anon;
set local request.jwt.claims = '{"role":"anon"}';
select is_empty($$ select month from public.schedules $$, 'anon cannot read drafts');
select is_empty($$ select id from public.schedule_shifts $$, 'anon cannot read draft shifts');
reset role;

select * from finish();
rollback;
